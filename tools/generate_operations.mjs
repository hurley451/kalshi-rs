#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const kalshiCoreRoot = resolveOption("--kalshicore-root") ?? process.env.KALSHICORE_ROOT;
if (!kalshiCoreRoot) {
  throw new Error("Set KALSHICORE_ROOT or pass --kalshicore-root <path>.");
}

const inventoryPath = path.join(
  path.resolve(kalshiCoreRoot),
  "sources",
  "official",
  "rest-openapi-operations.json"
);
const inventory = JSON.parse(await readFile(inventoryPath, "utf8"));
const operations = inventory.operations;
if (!Array.isArray(operations)) {
  throw new Error(`${inventoryPath} does not contain an operations array.`);
}

const outputPath = path.resolve(resolveOption("--out") ?? "src/generated/operations.rs");
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, render(inventory, operations), "utf8");
console.log(`Generated ${operations.length} operations at ${outputPath}`);

function render(inventory, operations) {
  return `// Generated by tools/generate_operations.mjs from KalshiCore official sources.
// Source: ${inventory.url}
// Version: ${inventory.version}
// SHA-256: ${inventory.sha256}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct KalshiOperation {
    pub operation_id: &'static str,
    pub method: &'static str,
    pub path: &'static str,
    pub summary: Option<&'static str>,
    pub tags: &'static [&'static str],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OfficialOperationSource {
    pub source_id: &'static str,
    pub url: &'static str,
    pub version: &'static str,
    pub sha256: &'static str,
    pub operation_count: usize,
}

pub const OFFICIAL_OPERATION_SOURCE: OfficialOperationSource = OfficialOperationSource {
    source_id: ${rustString(inventory.sourceId)},
    url: ${rustString(inventory.url)},
    version: ${rustString(inventory.version)},
    sha256: ${rustString(inventory.sha256)},
    operation_count: ${operations.length},
};

pub const OPERATIONS: &[KalshiOperation] = &[
${operations.map(renderOperation).join("\n")}
];

pub fn get_operation(operation_id: &str) -> Option<&'static KalshiOperation> {
    OPERATIONS
        .iter()
        .find(|operation| operation.operation_id == operation_id)
}
`;
}

function renderOperation(operation) {
  const summary = typeof operation.summary === "string" ? `Some(${rustString(operation.summary)})` : "None";
  const tags = Array.isArray(operation.tags)
    ? operation.tags.filter((tag) => typeof tag === "string").map(rustString).join(", ")
    : "";
  return `    KalshiOperation {
        operation_id: ${rustString(readString(operation, "operationId"))},
        method: ${rustString(readString(operation, "method").toUpperCase())},
        path: ${rustString(readString(operation, "path"))},
        summary: ${summary},
        tags: &[${tags}],
    },`;
}

function rustString(value) {
  return JSON.stringify(value);
}

function readString(body, name) {
  const value = body[name];
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`${name} must be a non-empty string.`);
  }
  return value;
}

function resolveOption(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}
